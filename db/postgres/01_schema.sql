-- PostgreSQL 用 DDL
-- テーブル/カラム構成は db/mysql/01_schema.sql と揃えること。
--
-- FK列のインデックスについて:
--   PostgreSQL は FK 列にインデックスを自動作成しない（MySQL/InnoDB は作る）。
--   両DBの条件を揃えるため、FK 列のインデックスは名前付きで明示的に定義する。

-- MySQL の ON UPDATE CURRENT_TIMESTAMP 相当
CREATE FUNCTION set_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at := CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$;

CREATE TABLE categories (
  id         bigint       GENERATED BY DEFAULT AS IDENTITY,
  parent_id  bigint       NULL,
  name       varchar(100) NOT NULL,
  sort_order int          NOT NULL DEFAULT 0,
  created_at timestamp(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamp(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT uq_categories_name UNIQUE (name),
  CONSTRAINT fk_categories_parent FOREIGN KEY (parent_id) REFERENCES categories (id)
);
CREATE INDEX idx_categories_parent_id ON categories (parent_id);
CREATE TRIGGER trg_categories_updated_at BEFORE UPDATE ON categories
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE customers (
  id         bigint       GENERATED BY DEFAULT AS IDENTITY,
  name       varchar(100) NOT NULL,
  email      varchar(255) NOT NULL,
  prefecture varchar(10)  NOT NULL,
  created_at timestamp(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamp(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id)
);
-- MySQL(utf8mb4_0900_ai_ci) に合わせ、大文字小文字を区別せず一意にする。
-- 式インデックスのため、検索で使うには WHERE lower(email) = lower(...) と書く必要がある。
CREATE UNIQUE INDEX uq_customers_email ON customers (lower(email));
CREATE TRIGGER trg_customers_updated_at BEFORE UPDATE ON customers
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE products (
  id          bigint       GENERATED BY DEFAULT AS IDENTITY,
  category_id bigint       NOT NULL,
  name        varchar(200) NOT NULL,
  price       int          NOT NULL,
  created_at  timestamp(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at  timestamp(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT fk_products_category FOREIGN KEY (category_id) REFERENCES categories (id),
  CONSTRAINT ck_products_price CHECK (price >= 0)
);
CREATE INDEX idx_products_category_id ON products (category_id);
CREATE TRIGGER trg_products_updated_at BEFORE UPDATE ON products
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE orders (
  id          bigint       GENERATED BY DEFAULT AS IDENTITY,
  customer_id bigint       NOT NULL,
  -- 注文ステータスのマスタは CHECK 制約で管理する（README参照）
  status      varchar(20)  NOT NULL DEFAULT 'pending',
  ordered_at  timestamp(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_at  timestamp(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at  timestamp(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT fk_orders_customer FOREIGN KEY (customer_id) REFERENCES customers (id),
  CONSTRAINT ck_orders_status CHECK (status IN ('pending', 'paid', 'shipped', 'delivered', 'cancelled'))
);
CREATE INDEX idx_orders_customer_id ON orders (customer_id);
CREATE TRIGGER trg_orders_updated_at BEFORE UPDATE ON orders
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE order_items (
  id         bigint       GENERATED BY DEFAULT AS IDENTITY,
  order_id   bigint       NOT NULL,
  product_id bigint       NOT NULL,
  quantity   int          NOT NULL,
  unit_price int          NOT NULL,
  created_at timestamp(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamp(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  -- order_id の FK はこの複合ユニークの先頭列で賄う
  CONSTRAINT uq_order_items_order_product UNIQUE (order_id, product_id),
  CONSTRAINT fk_order_items_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE,
  CONSTRAINT fk_order_items_product FOREIGN KEY (product_id) REFERENCES products (id),
  CONSTRAINT ck_order_items_quantity CHECK (quantity > 0),
  CONSTRAINT ck_order_items_unit_price CHECK (unit_price >= 0)
);
CREATE INDEX idx_order_items_product_id ON order_items (product_id);
CREATE TRIGGER trg_order_items_updated_at BEFORE UPDATE ON order_items
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
